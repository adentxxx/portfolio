/**
 * Russian hanging prepositions: a short word at the end of a line looks broken,
 * so the space after a preposition becomes a non-breaking space.
 * Idempotent: an existing NBSP is left alone.
 */
const PREPOSITIONS = [
  "из-за",
  "из-под",
  "благодаря",
  "навстречу",
  "посередине",
  "вследствие",
  "наподобие",
  "напротив",
  "посреди",
  "согласно",
  "вопреки",
  "помимо",
  "впереди",
  "сквозь",
  "внутри",
  "вокруг",
  "вместо",
  "между",
  "передо",
  "перед",
  "против",
  "возле",
  "после",
  "около",
  "вдоль",
  "среди",
  "через",
  "вроде",
  "сверх",
  "мимо",
  "кроме",
  "надо",
  "безо",
  "подо",
  "обо",
  "ото",
  "изо",
  "вне",
  "меж",
  "близ",
  "над",
  "под",
  "при",
  "про",
  "ради",
  "без",
  "для",
  "от",
  "до",
  "за",
  "из",
  "ко",
  "на",
  "об",
  "по",
  "со",
  "во",
  "в",
  "к",
  "о",
  "с",
  "у",
].sort((a, b) => b.length - a.length);

const PREPOSITION_RE = new RegExp(
  `(?<![\\p{L}\\p{N}_])(${PREPOSITIONS.join("|")})[ \\t]+(?=\\S)`,
  "giu",
);

export function nbsp(text: string): string {
  if (!text || !/[А-Яа-яЁё]/.test(text)) return text;
  return text.replace(PREPOSITION_RE, (_match, prep: string) => `${prep}\u00A0`);
}
